/**
 * Renders the generated reference documents from a {@link scanProject} result.
 *
 * Output is deterministic (sorted, no timestamps) so `docs:check` can compare it byte-for-byte with the
 * committed files and fail when the code and the documents disagree.
 */
import {
  layers,
  layerEdges,
  layerViolations,
  loadLayeringBaseline,
  reachableFrom,
} from "./lib.mjs";

const banner = (name) =>
  `<!-- GENERATED by scripts/docs/generate-docs.mjs — do not edit by hand. Run \`npm run docs:generate\`. -->\n` +
  `<!-- Source of truth: the TypeScript modules under src/. This file is checked for freshness by \`npm run docs:check\` and the test suite. -->\n\n` +
  (name ? `` : ``);

/** First sentence (or first paragraph line) of a doc comment, flattened to one line. */
export function summarize(text, max = 220) {
  if (!text) return "";
  const paragraph = text.split(/\n\s*\n/)[0].replace(/\s+/g, " ").trim();
  const match = paragraph.match(/^(.+?[.!?])(\s|$)/);
  const sentence = (match ? match[1] : paragraph).trim();
  return sentence.length > max ? `${sentence.slice(0, max - 1)}…` : sentence;
}

const cell = (text) => String(text ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");

function groupByLayer(modules) {
  const groups = new Map();
  for (const mod of modules.values()) {
    if (!groups.has(mod.layer)) groups.set(mod.layer, []);
    groups.get(mod.layer).push(mod);
  }
  for (const list of groups.values()) list.sort((a, b) => a.path.localeCompare(b.path));
  return groups;
}

const layerOrder = ["math", "cell-complex", "movement", "examples", "world-assets", "world-objects", "authoring", "runtime", "ui", "glue", "render", "root"];

export function renderArchitectureReference(modules) {
  const groups = groupByLayer(modules);
  const reachable = reachableFrom(modules);
  const edges = layerEdges(modules);
  const baseline = loadLayeringBaseline();
  const out = [];

  out.push(banner());
  out.push("# Architecture reference (generated)\n");
  out.push(
    "This reference is produced from the source code. For the *meaning* of the modules — the mathematical model they implement — " +
      "read [../MATHEMATICAL_MODEL.md](../MATHEMATICAL_MODEL.md) and [../ARCHITECTURE.md](../ARCHITECTURE.md). " +
      "For every exported symbol see [API_REFERENCE.md](API_REFERENCE.md).\n",
  );

  const totalLines = [...modules.values()].reduce((sum, m) => sum + m.lines, 0);
  out.push(`**${modules.size} modules, ${totalLines.toLocaleString("en-US")} lines** under \`src/\`.\n`);

  out.push("## Layers\n");
  out.push("A module belongs to the layer named by its first path segment under `src/`. \"May import\" is the *intended* rule; violations are listed under [Layering debt](#layering-debt).\n");
  out.push("| Layer | Modules | Lines | May import | Purpose |");
  out.push("| --- | ---: | ---: | --- | --- |");
  for (const name of layerOrder) {
    const list = groups.get(name);
    if (!list) continue;
    const rule = layers[name];
    const lines = list.reduce((sum, m) => sum + m.lines, 0);
    const may = rule.may.includes("*") ? "anything" : rule.may.length === 0 ? "nothing" : rule.may.map((l) => `\`${l}\``).join(", ");
    out.push(`| \`${name}\` | ${list.length} | ${lines.toLocaleString("en-US")} | ${may} | ${cell(rule.description)} |`);
  }
  out.push("");

  out.push("## Layer dependency graph\n");
  out.push("Edges are *actual* imports aggregated by layer; the label is the number of importing module pairs.\n");
  out.push("```mermaid\nflowchart LR");
  for (const name of layerOrder) if (groups.has(name)) out.push(`  ${name.replace(/-/g, "_")}["${name}"]`);
  for (const [edge, count] of [...edges].sort()) {
    const [from, to] = edge.split(" -> ");
    const rule = layers[from];
    const allowed = rule && (rule.may.includes("*") || rule.may.includes(to));
    out.push(`  ${from.replace(/-/g, "_")} ${allowed ? "-->" : "-.->"}|${count}| ${to.replace(/-/g, "_")}`);
  }
  out.push("```\n");
  out.push("Dashed edges violate the intended layering (see below).\n");

  out.push("## Layering debt\n");
  const violations = layerViolations(modules);
  if (violations.length === 0) {
    out.push("None: every import respects the intended layering.\n");
  } else {
    out.push(
      "These imports break the intended layering. They are frozen in `scripts/docs/layering-baseline.json`: " +
        "`npm run docs:check` fails on any *new* violation, and fixing one should remove it from the baseline.\n",
    );
    out.push("| Importing module | Imported module | Layer edge |");
    out.push("| --- | --- | --- |");
    for (const v of violations.sort((a, b) => (a.from + a.to).localeCompare(b.from + b.to))) {
      out.push(`| \`${v.from}\` | \`${v.to}\` | ${v.edge} |`);
    }
    out.push("");
  }
  if (baseline.length > violations.length) {
    out.push(`> The baseline lists ${baseline.length - violations.length} edge(s) that no longer violate the rules; regenerate it.\n`);
  }

  out.push("## Module index\n");
  for (const name of layerOrder) {
    const list = groups.get(name);
    if (!list) continue;
    out.push(`### \`${name}\`\n`);
    out.push("| Module | Lines | Summary | Imports |");
    out.push("| --- | ---: | --- | --- |");
    for (const mod of list) {
      const imports = mod.imports.map((i) => `\`${i.replace(/\.ts$/, "")}\``).join(", ");
      out.push(`| \`${mod.path}\` | ${mod.lines} | ${cell(summarize(mod.header)) || "_undocumented_"} | ${cell(imports) || "—"} |`);
    }
    out.push("");
  }

  out.push("## Reachability\n");
  const unreachable = [...modules.keys()].filter((p) => !reachable.has(p)).sort();
  if (unreachable.length === 0) {
    out.push("Every module is reachable from `src/main.ts` (including the geometry worker entry).\n");
  } else {
    out.push("Modules not reachable from `src/main.ts`. They are exercised only by tests; review whether they are still needed.\n");
    for (const p of unreachable) out.push(`- \`${p}\``);
    out.push("");
  }

  return out.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}

export function renderApiReference(modules) {
  const groups = groupByLayer(modules);
  const out = [];
  out.push(banner());
  out.push("# API reference (generated)\n");
  out.push(
    "Every exported declaration, grouped by layer and module, with the first sentence of its JSDoc. " +
      "Read the source for the full contract. Module-level overviews are in [ARCHITECTURE_REFERENCE.md](ARCHITECTURE_REFERENCE.md).\n",
  );
  for (const name of layerOrder) {
    const list = groups.get(name);
    if (!list) continue;
    out.push(`## \`${name}\`\n`);
    for (const mod of list) {
      out.push(`### \`${mod.path}\`\n`);
      if (mod.header) out.push(`${summarize(mod.header, 400)}\n`);
      if (mod.exports.length === 0) {
        out.push("_No exports._\n");
        continue;
      }
      out.push("| Kind | Name | Summary |");
      out.push("| --- | --- | --- |");
      for (const e of mod.exports) {
        out.push(`| ${e.kind} | \`${e.name}\` | ${cell(summarize(e.doc)) || "_undocumented_"} |`);
      }
      out.push("");
    }
  }
  return out.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}
