"""Install the agents-md drop-in into the repository that contains it.

Copy the ``agents-md`` folder into ``<repository>/.agents/`` and run ``python .agents/agents-md/install.py``.
Installing creates the fragment directory ``.agents/agents.md.d/`` from the template fragments in
``.agents/agents-md/agents.md.d/`` if it does not exist yet (an existing directory is never touched), writes two launchers into
``<repository>/_scripts/`` that call ``.agents/agents-md/agents-md.py`` (``agents-md.cmd`` for Windows shells and
``agents-md`` for POSIX shells), and adds the generated files to ``.gitignore``. Running it again changes nothing.
Standard library only.
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

COMMAND = "agents-md"
IGNORED = ("/AGENTS.md", "/CLAUDE.md", "/_scripts/", "/.agents/.state/")


def main() -> int:
    """Install the drop-in into the repository two levels above this file, and say what changed."""
    tool_dir = Path(__file__).resolve().parent
    if tool_dir.parent.name != ".agents":
        print(f"error: {tool_dir} is not inside a .agents/ folder; copy it to <repository>/.agents/ first")
        return 2

    root = tool_dir.parents[1]
    for change in install(root, tool_dir.name):
        print(change)
    print(f"installed; run: _scripts/{COMMAND} build")
    return 0


def install(root: Path, tool_name: str) -> list[str]:
    """Create the fragment directory, the launchers and the ignore rules, returning one line per change made."""
    changes: list[str] = []

    # The fragments are the source of truth. A new repository starts from the template fragments; an existing
    # directory is left alone so that fragments the project has edited or deleted are not brought back.
    fragments = root / ".agents" / "agents.md.d"
    if not fragments.is_dir():
        template = root / ".agents" / tool_name / "agents.md.d"
        if template.is_dir():
            shutil.copytree(template, fragments)
        else:
            fragments.mkdir(parents=True)
        changes.append("created .agents/agents.md.d/ from the template fragments")

    # Launchers only call the drop-in's script, found relative to their own location so the repository can move.
    launchers = {
        f"{COMMAND}.cmd": (f'@echo off\npython "%~dp0..\\.agents\\{tool_name}\\{COMMAND}.py" %*\n', "\r\n"),
        COMMAND: (
            "#!/bin/sh\n"
            f'script="$(dirname "$0")/../.agents/{tool_name}/{COMMAND}.py"\n'
            'if command -v python3 >/dev/null 2>&1; then exec python3 "$script" "$@"; fi\n'
            'exec python "$script" "$@"\n',
            "\n",
        ),
    }
    scripts = root / "_scripts"
    scripts.mkdir(exist_ok=True)
    for name, (text, newline) in launchers.items():
        if _write_if_changed(scripts / name, text, newline):
            changes.append(f"wrote _scripts/{name}")
    (scripts / COMMAND).chmod(0o755)

    # The generated files never belong in Git.
    missing = _missing_ignore_lines(root / ".gitignore")
    if missing:
        _append_ignore_lines(root / ".gitignore", missing)
        changes.append(f"added to .gitignore: {', '.join(missing)}")
    return changes


def _write_if_changed(path: Path, text: str, newline: str) -> bool:
    """Write text with the given line ending unless the file already holds exactly that; return whether it wrote."""
    if path.is_file() and path.read_bytes() == text.replace("\n", newline).encode("utf-8"):
        return False
    path.write_text(text, encoding="utf-8", newline=newline)
    return True


def _missing_ignore_lines(gitignore: Path) -> list[str]:
    present = set(gitignore.read_text(encoding="utf-8").splitlines()) if gitignore.is_file() else set()
    return [line for line in IGNORED if line not in present]


def _append_ignore_lines(gitignore: Path, lines: list[str]) -> None:
    existing = gitignore.read_text(encoding="utf-8") if gitignore.is_file() else ""
    separator = "" if not existing or existing.endswith("\n") else "\n"
    block = "\n# Generated by the agents-md drop-in (.agents/agents-md/)\n" + "\n".join(lines) + "\n"
    gitignore.write_text(existing + separator + block, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    sys.exit(main())
