"""Generate AGENTS.md and CLAUDE.md from the instruction fragments in .agents/agents.md.d/.

The generated files are gitignored; the fragments are the source of truth. Lines that someone wrote directly into a
generated file, and that come from no fragment, are moved into ``custom.md`` (from AGENTS.md) or ``custom-claude.md``
(from CLAUDE.md) before the files are regenerated, so hand edits are never lost.

This file is part of the ``agents-md`` drop-in: the folder ``.agents/agents-md/`` is copied into a repository and
installed with ``python .agents/agents-md/install.py``, which writes the launchers ``_scripts/agents-md.cmd`` and
``_scripts/agents-md``. Run ``_scripts/agents-md build`` (or ``python .agents/agents-md/agents-md.py build``) to
regenerate the files and ``_scripts/agents-md check`` to see whether a build is needed. The design is in
``.agents/agents-md/agents-md-tool-design.md``. Standard library only.
"""

from __future__ import annotations

import argparse
import datetime
import difflib
import io
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

FRAGMENT_DIR = Path(".agents") / "agents.md.d"
STATE_DIR = Path(".agents") / ".state" / "agents-md"
NOTICE = (
    "<!-- Generated by .agents/agents-md/agents-md.py from .agents/agents.md.d/. Do not edit; edit the fragments. -->"
)
IMPORT_LINE = "@AGENTS.md"


def main(argv: list[str] | None = None) -> int:
    """Run the ``build`` or ``check`` command and return the process exit code.

    Parameters
    ----------
    argv
        Command-line arguments without the program name; ``None`` reads ``sys.argv``.

    Returns
    -------
    int
        ``0`` on success or when no build is needed, ``1`` when ``check`` finds that a build is needed, ``2`` when a
        fragment is invalid.
    """
    # Echo hand-written lines safely even on a console that cannot encode every character.
    for stream in (sys.stdout, sys.stderr):
        if isinstance(stream, io.TextIOWrapper):
            stream.reconfigure(errors="replace")

    parser = argparse.ArgumentParser(prog="agents-md", description=__doc__.splitlines()[0])
    commands = parser.add_subparsers(dest="command", required=True)
    build = commands.add_parser("build", help="regenerate AGENTS.md and CLAUDE.md, keeping hand-written lines")
    build.add_argument("--root", type=Path, help=ROOT_HELP)
    build.add_argument("--dry-run", action="store_true", help="show what would change without writing anything")
    check = commands.add_parser("check", help="report whether a build is needed, without writing anything")
    check.add_argument("--root", type=Path, help=ROOT_HELP)
    args = parser.parse_args(argv)

    # Work out everything a build would do before touching any file.
    try:
        root = (args.root or installed_root()).resolve()
        plans = plan_build(root, datetime.date.today())
    except AgentsMdError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2

    if args.command == "check":
        return _report_check(plans)
    if args.dry_run:
        return _report_dry_run(plans)
    return _write_build(root, plans)


def plan_build(root: Path, today: datetime.date) -> list[OutputPlan]:
    """Work out what a build would write, without writing anything.

    Parameters
    ----------
    root
        Repository root holding ``AGENTS.md``, ``CLAUDE.md`` and ``.agents/agents.md.d/``.
    today
        Date recorded in the comment above each block of custom lines.

    Returns
    -------
    list[OutputPlan]
        One plan per generated file, in the order AGENTS.md, CLAUDE.md.

    Raises
    ------
    AgentsMdError
        If a fragment is invalid. The message lists every invalid fragment.
    """
    directory = root / FRAGMENT_DIR
    fragments = load_fragments(directory)

    # Find custom lines in every output against the fragments as they are now, before any custom fragment grows.
    # Lines the last build wrote are not custom either, so editing a fragment does not turn its old text into custom.
    found: list[tuple[Output, str | None, Comparison]] = []
    for output in OUTPUTS:
        current = _read_if_present(root / output.file_name)
        last_build = _read_if_present(root / STATE_DIR / output.file_name)
        comparison = compare(current, fragments, output, last_build) if current is not None else Comparison()
        found.append((output, current, comparison))

    # Append the custom lines to their custom fragments, so the regenerated outputs contain them.
    custom_texts: dict[str, str] = {}
    for output, _, comparison in found:
        if comparison.custom_blocks:
            existing = _read_if_present(directory / output.custom_name)
            text = append_custom_blocks(existing, output, comparison.custom_blocks, today)
            fragments[output.custom_name] = parse_fragment(output.custom_name, text)
            custom_texts[output.custom_name] = text

    return [
        OutputPlan(
            output=output,
            current=current,
            comparison=comparison,
            new_text=render(fragments, output),
            custom_text=custom_texts.get(output.custom_name),
        )
        for output, current, comparison in found
    ]


# ---------------------------------------------------------------------------------------------------------------------
# Commands: what each one prints and writes


def _write_build(root: Path, plans: list[OutputPlan]) -> int:
    """Write the custom fragments, then the outputs, and say what happened."""
    # Write custom fragments first: if a later write fails, the hand-written lines are already safe.
    for plan in plans:
        _print_findings(plan, moving="moved")
        if plan.custom_text is not None:
            path = root / FRAGMENT_DIR / plan.output.custom_name
            path.parent.mkdir(parents=True, exist_ok=True)
            _write_text(path, plan.custom_text)

    # Rewrite only the outputs whose content changed, and remember what was written for the next comparison.
    (root / STATE_DIR).mkdir(parents=True, exist_ok=True)
    for plan in plans:
        name = plan.output.file_name
        if plan.current == plan.new_text:
            print(f"{name} is up to date")
        else:
            _write_text(root / name, plan.new_text)
            print(f"wrote {name}")
        _write_text(root / STATE_DIR / name, plan.new_text)
    return 0


def _report_dry_run(plans: list[OutputPlan]) -> int:
    """Print the custom lines a build would move and a diff of each output."""
    for plan in plans:
        _print_findings(plan, moving="would move")
        name = plan.output.file_name
        diff = difflib.unified_diff(
            (plan.current or "").splitlines(),
            plan.new_text.splitlines(),
            fromfile=f"{name} (now)",
            tofile=f"{name} (after build)",
            lineterm="",
        )
        lines = list(diff)
        print("\n".join(lines) if lines else f"{name}: no change")
    return 0


def _report_check(plans: list[OutputPlan]) -> int:
    """Print the state of each output and return 1 when a build is needed."""
    needs_build = False
    for plan in plans:
        name = plan.output.file_name
        custom_count = plan.comparison.custom_line_count()
        if plan.current is None:
            print(f"{name}: missing")
        elif custom_count:
            print(f"{name}: {custom_count} line(s) not from any fragment")
        elif plan.current != plan.new_text:
            print(f"{name}: out of date")
        else:
            print(f"{name}: up to date")
            continue
        needs_build = True
        _print_findings(plan, moving="a build would move")

    if needs_build:
        print("run: _scripts/agents-md build")
    return 1 if needs_build else 0


def _print_findings(plan: OutputPlan, moving: str) -> None:
    """Print the custom, edited and missing lines found in one output."""
    name = plan.output.file_name
    custom_path = f"{FRAGMENT_DIR.as_posix()}/{plan.output.custom_name}"
    comparison = plan.comparison

    if comparison.custom_blocks:
        print(f"{moving} {comparison.custom_line_count()} line(s) from {name} to {custom_path}:")
        for block in comparison.custom_blocks:
            for line in block.lines:
                print(f"  + {line}")
    for fragment_line, found_line in comparison.edited:
        print(
            f"possibly edited in {name}: {found_line!r} replaces {fragment_line!r}; "
            f"if the edit is meant, put it in the fragment and delete it from {custom_path}"
        )
    for fragment_name, line in comparison.missing:
        print(
            f"warning: {name} lacks a line of {fragment_name}, which a build restores; "
            f"delete it from the fragment if the removal is meant: {line!r}"
        )


def _read_if_present(path: Path) -> str | None:
    """Return the text of a file, or ``None`` when it does not exist."""
    return path.read_text(encoding="utf-8") if path.is_file() else None


def _write_text(path: Path, text: str) -> None:
    """Write UTF-8 text with LF line endings on every platform."""
    path.write_text(text, encoding="utf-8", newline="\n")


# ---------------------------------------------------------------------------------------------------------------------
# Outputs and rendering


@dataclass(frozen=True)
class Output:
    """A generated file, the fragments that feed it, and the fragment that receives its custom lines."""

    target: str
    file_name: str
    custom_name: str


OUTPUTS = (
    Output(target="all", file_name="AGENTS.md", custom_name="custom.md"),
    Output(target="claude", file_name="CLAUDE.md", custom_name="custom-claude.md"),
)


@dataclass(frozen=True)
class OutputPlan:
    """What a build would do to one generated file.

    ``current`` is the file's text now (``None`` when absent), ``new_text`` what the build writes, and
    ``custom_text`` the new full text of the custom fragment when lines move into it (``None`` otherwise).
    """

    output: Output
    current: str | None
    comparison: Comparison
    new_text: str
    custom_text: str | None


def render(fragments: dict[str, Fragment], output: Output) -> str:
    """Return the text of one generated file.

    The text is the generated-file notice, then (for CLAUDE.md) the ``@AGENTS.md`` import, then the body of every
    enabled fragment of the output's target, ordered by ``order`` and then by file name. Each body is preceded by a
    comment naming its fragment. Blocks are separated by one blank line and the text ends with a newline.
    """
    blocks = [NOTICE]
    if output.target == "claude":
        blocks.append(IMPORT_LINE)
    for fragment in sorted(fragments.values(), key=lambda fragment: (fragment.order, fragment.name)):
        if fragment.enabled and fragment.target == output.target and fragment.body:
            blocks.append(f"{_source_comment(fragment.name)}\n{fragment.body}")
    return "\n\n".join(blocks) + "\n"


def _source_comment(fragment_name: str) -> str:
    return f"<!-- from {FRAGMENT_DIR.as_posix()}/{fragment_name} -->"


_SOURCE_COMMENT = re.compile(r"<!-- from \.agents/agents\.md\.d/\S+ -->")
# Any generated-file notice, including one written by an older version with a different wording.
_NOTICE = re.compile(r"<!-- Generated by .* from \.agents/agents\.md\.d/.* -->")


def _is_generated(line: str, output: Output) -> bool:
    """Tell whether a line is one the generator writes itself, rather than one taken from a fragment."""
    return bool(_NOTICE.fullmatch(line) or _SOURCE_COMMENT.fullmatch(line)) or (
        output.target == "claude" and line == IMPORT_LINE
    )


# ---------------------------------------------------------------------------------------------------------------------
# Comparing a generated file with the fragments


@dataclass(frozen=True)
class CustomBlock:
    """Consecutive custom lines, and the last heading above them (``None`` when there is none)."""

    after_heading: str | None
    lines: tuple[str, ...]


@dataclass
class Comparison:
    """What a generated file contains beyond, or lacks from, its fragments.

    ``custom_blocks`` are the lines that come from no fragment. ``edited`` pairs a fragment line with the custom line
    that took its place. ``missing`` lists other fragment lines absent from the file, with their fragment's name.
    """

    custom_blocks: list[CustomBlock] = field(default_factory=list)
    edited: list[tuple[str, str]] = field(default_factory=list)
    missing: list[tuple[str, str]] = field(default_factory=list)

    def custom_line_count(self) -> int:
        """Return the number of non-blank custom lines."""
        return sum(1 for block in self.custom_blocks for line in block.lines if line)


def compare(current: str, fragments: dict[str, Fragment], output: Output, last_build: str | None = None) -> Comparison:
    """Compare the current text of a generated file with what its fragments produce.

    A line is custom when, after removing trailing whitespace, it is not blank, not written by the generator itself,
    not a line of any fragment (enabled or not, of any target), and not a line of ``last_build``, the text the last
    build wrote to this file. Consecutive custom lines, with the blank lines between them, form one block.
    """
    known = {line for fragment in fragments.values() for line in fragment.body.split("\n")}
    if last_build is not None:
        known.update(line.rstrip() for line in last_build.splitlines())
    current_lines = [line.rstrip() for line in current.splitlines()]
    comparison = Comparison(custom_blocks=_custom_blocks(current_lines, known, output))

    # A fragment line can only have been removed from the file if the last build wrote it there; a line added to a
    # fragment since then is simply not built yet. Without a saved last build, every absent line is a suspect.
    expected_lines = render(fragments, output).splitlines()
    present = set(current_lines)
    written = None if last_build is None else {line.rstrip() for line in last_build.splitlines()}

    def removed(line: str) -> bool:
        return bool(line) and line not in present and (written is None or line in written)

    # Pair fragment lines that disappeared with the custom lines that appeared in their place.
    matcher = difflib.SequenceMatcher(None, expected_lines, current_lines, autojunk=False)
    for tag, i1, i2, j1, j2 in matcher.get_opcodes():
        if tag != "replace":
            continue
        lost = [line for line in expected_lines[i1:i2] if removed(line)]
        added = [
            line for line in current_lines[j1:j2] if line and line not in known and not _is_generated(line, output)
        ]
        comparison.edited.extend(zip(lost, added, strict=False))

    # Report every other fragment line that is gone, once, with the fragment it belongs to.
    paired = {fragment_line for fragment_line, _ in comparison.edited}
    origins = _line_origins(fragments, output)
    for line in dict.fromkeys(expected_lines):
        if line in origins and removed(line) and line not in paired:
            comparison.missing.append((origins[line], line))
    return comparison


def _custom_blocks(lines: list[str], known: set[str], output: Output) -> list[CustomBlock]:
    """Group the custom lines of a file into blocks, each with the last heading above it."""
    blocks: list[CustomBlock] = []
    pending: list[str] = []
    heading: str | None = None
    block_heading: str | None = None
    in_fence = False

    def flush() -> None:
        while pending and not pending[-1]:
            pending.pop()
        if pending:
            blocks.append(CustomBlock(after_heading=block_heading, lines=tuple(pending)))
        pending.clear()

    for line in lines:
        # Classify the line: a blank line extends an open block, a known line closes it, anything else is custom.
        if not line:
            if pending:
                pending.append(line)
        elif line in known or _is_generated(line, output):
            flush()
        else:
            if not pending:
                block_heading = heading
            pending.append(line)

        # Track the last Markdown heading, ignoring `#` lines inside fenced code blocks (shell comments).
        if line.startswith("```"):
            in_fence = not in_fence
        elif line.startswith("#") and not in_fence:
            heading = line.lstrip("#").strip()

    flush()
    return blocks


def _line_origins(fragments: dict[str, Fragment], output: Output) -> dict[str, str]:
    """Map each line of the output's enabled fragments to the name of the first fragment containing it."""
    origins: dict[str, str] = {}
    for fragment in sorted(fragments.values(), key=lambda fragment: (fragment.order, fragment.name)):
        if fragment.enabled and fragment.target == output.target:
            for line in fragment.body.split("\n"):
                origins.setdefault(line, fragment.name)
    return origins


def append_custom_blocks(existing: str | None, output: Output, blocks: list[CustomBlock], today: datetime.date) -> str:
    """Return the text of a custom fragment with new blocks appended.

    A missing custom fragment is created with ``order: 1000`` and the output's target. Each block is preceded by a
    comment recording the date, the file it was found in, and the heading above it.
    """
    if existing is None:
        header = ["---", "order: 1000", f"description: Lines found in {output.file_name} that came from no fragment."]
        if output.target != "all":
            header.append(f"target: {output.target}")
        text = "\n".join([*header, "---", ""])
    else:
        text = existing.rstrip("\n") + "\n"

    for block in blocks:
        # `--` would end the HTML comment early, so it is shortened inside the heading text.
        where = f'after "{block.after_heading.replace("--", "-")}"' if block.after_heading else "at the start"
        text += f"\n<!-- found {today.isoformat()} in {output.file_name} {where} -->\n" + "\n".join(block.lines) + "\n"
    return text


# ---------------------------------------------------------------------------------------------------------------------
# Fragments


class AgentsMdError(Exception):
    """An invalid fragment; the message names the fragment and the problem."""


@dataclass(frozen=True)
class Fragment:
    """One instruction fragment: its file name, frontmatter fields and Markdown body."""

    name: str
    order: int
    description: str
    target: str
    enabled: bool
    body: str


TARGETS = ("all", "claude")
_FIELDS = ("order", "description", "target", "enabled")
_INTEGER = re.compile(r"[+-]?\d+")


def load_fragments(directory: Path) -> dict[str, Fragment]:
    """Read and validate every ``*.md`` fragment in a directory.

    Parameters
    ----------
    directory
        The fragment directory. A missing directory holds no fragments.

    Returns
    -------
    dict[str, Fragment]
        Fragments keyed by file name.

    Raises
    ------
    AgentsMdError
        If any fragment is invalid. The message lists every problem, one per line.
    """
    if not directory.is_dir():
        return {}

    fragments: dict[str, Fragment] = {}
    problems: list[str] = []
    for path in sorted(directory.glob("*.md")):
        try:
            fragments[path.name] = parse_fragment(path.name, path.read_text(encoding="utf-8"))
        except AgentsMdError as error:
            problems.append(str(error))
    if problems:
        raise AgentsMdError("invalid fragment(s) in " + FRAGMENT_DIR.as_posix() + ":\n" + "\n".join(problems))
    return fragments


def parse_fragment(name: str, text: str) -> Fragment:
    """Parse the text of one fragment.

    The text opens with a ``---`` line, then ``key: value`` lines, then a closing ``---`` line, then the Markdown body.
    Values are integers, ``true``, ``false`` or strings, optionally quoted. Allowed keys are ``order`` (required
    integer), ``description`` (required), ``target`` (``all`` or ``claude``, default ``all``) and ``enabled``
    (default ``true``). Trailing whitespace is removed from body lines, and leading and trailing blank lines from the
    body.

    Raises
    ------
    AgentsMdError
        If the frontmatter is missing, unclosed, malformed, has an unknown or repeated key, or a field has a wrong
        value. The message starts with the fragment's name.
    """
    # Split the frontmatter from the body.
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        raise AgentsMdError(f"{name}: must start with a '---' line opening the frontmatter")
    closing = next((index for index in range(1, len(lines)) if lines[index].strip() == "---"), None)
    if closing is None:
        raise AgentsMdError(f"{name}: the frontmatter is not closed by a '---' line")
    values = _parse_frontmatter(name, lines[1:closing])
    body = "\n".join(line.rstrip() for line in lines[closing + 1 :]).strip("\n")

    # Check each field against the format of the design (§3).
    unknown = sorted(set(values) - set(_FIELDS))
    if unknown:
        raise AgentsMdError(f"{name}: unknown field(s) {', '.join(unknown)}; allowed: {', '.join(_FIELDS)}")
    order = values.get("order")
    if "order" not in values:
        raise AgentsMdError(f"{name}: missing required field 'order'")
    if not isinstance(order, int) or isinstance(order, bool):
        raise AgentsMdError(f"{name}: 'order' must be an integer, found {order!r}")
    description = values.get("description")
    if not isinstance(description, str) or not description:
        raise AgentsMdError(f"{name}: missing required field 'description' (one sentence saying what it is for)")
    target = values.get("target", "all")
    if target not in TARGETS:
        raise AgentsMdError(f"{name}: 'target' must be one of {', '.join(TARGETS)}, found {target!r}")
    enabled = values.get("enabled", True)
    if not isinstance(enabled, bool):
        raise AgentsMdError(f"{name}: 'enabled' must be true or false, found {enabled!r}")

    return Fragment(name=name, order=order, description=description, target=str(target), enabled=enabled, body=body)


def _parse_frontmatter(name: str, lines: list[str]) -> dict[str, str | int | bool]:
    """Parse ``key: value`` lines; blank lines and ``#`` comment lines are skipped."""
    values: dict[str, str | int | bool] = {}
    for number, line in enumerate(lines, start=2):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        key, separator, raw = line.partition(":")
        key = key.strip()
        if not separator or not key:
            raise AgentsMdError(f"{name} line {number}: expected 'key: value', found {line!r}")
        if key in values:
            raise AgentsMdError(f"{name} line {number}: field '{key}' appears twice")
        values[key] = _parse_scalar(raw.strip())
    return values


def _parse_scalar(raw: str) -> str | int | bool:
    """Read a frontmatter value: a quoted string, ``true``, ``false``, an integer, or a plain string."""
    if len(raw) >= 2 and raw[0] == raw[-1] and raw[0] in "\"'":
        return raw[1:-1]
    if raw in ("true", "false"):
        return raw == "true"
    if _INTEGER.fullmatch(raw):
        return int(raw)
    return raw


